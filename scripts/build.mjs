/**
 * Build the Client half of the solids-world Harness plugin.
 *
 *   node scripts/build.mjs
 *
 * Steps
 *  1. generate `src/atlas/three/builders-map.ts` (the desktop app used Vite's
 *     `import.meta.glob`, which esbuild does not support);
 *  2. scope the desktop stylesheet to `.sw-atlas` so it cannot restyle the host
 *     page, and append the panel shell styles;
 *  3. bundle sources as an IIFE, with `react` resolved to the host instance;
 *  4. wrap the bundle in the `window.__ModuleLoader__.load` factory contract.
 *
 * Build-time dependencies (esbuild, postcss) are resolved from the solids-world
 * checkout named by SOLIDS_WORLD_SRC (default: the sibling directory). The
 * installed package only needs the emitted `client.js`.
 */

import { createRequire } from 'node:module'
import { existsSync, readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const packageRoot = path.resolve(here, '..')
const solidsWorld = process.env.SOLIDS_WORLD_SRC
  ? path.resolve(process.env.SOLIDS_WORLD_SRC)
  : path.resolve(packageRoot, '..', 'solids-world')

// Toolchain resolution: the package's own node_modules first (so this folder can
// be built after `npm install` anywhere), then the solids-world checkout.
const moduleDirs = [path.join(packageRoot, 'node_modules'), path.join(solidsWorld, 'node_modules')].filter(
  (dir) => existsSync(dir),
)

function requireTool(name) {
  for (const dir of moduleDirs) {
    if (!existsSync(path.join(dir, name))) continue
    try {
      return createRequire(path.join(dir, 'resolve-from.js'))(name)
    } catch {
      // Try the next location.
    }
  }
  return null
}

const esbuild = requireTool('esbuild')
const postcss = requireTool('postcss')

if (esbuild === null || postcss === null) {
  console.error(`[build] missing build tooling (${esbuild === null ? 'esbuild ' : ''}${postcss === null ? 'postcss' : ''})`)
  console.error(`[build] searched: ${moduleDirs.length > 0 ? moduleDirs.join(', ') : '(nothing found)'}`)
  console.error('[build] run `npm install` here, or set SOLIDS_WORLD_SRC to a checkout that has these packages.')
  process.exit(1)
}

// The Client module id must equal the package name (the module loader keys on it),
// so read it from the manifest instead of duplicating it here.
const PACKAGE_NAME = JSON.parse(readFileSync(path.join(packageRoot, 'package.json'), 'utf8')).name
const SCOPE = '.sw-atlas'

/* ------------------------------------------------------------------ builders */

const BUILDER_DIR = path.join(packageRoot, 'src', 'atlas', 'three', 'builders')
const BUILDER_FAMILIES = new Set([
  'crystal-structure-',
  'lattice-bravais-',
  'orbital-',
  'bohr-atom-',
  'symmetry-elements-',
  'lattice-wave-',
])

function generateBuildersMap() {
  const ids = readdirSync(BUILDER_DIR)
    .filter((file) => file.endsWith('.ts') && !file.includes('.test.'))
    .map((file) => file.slice(0, -3))
    .filter((id) => !BUILDER_FAMILIES.has(id))
    .sort()
  const lines = [
    '// Generated by scripts/build.mjs. Do not edit.',
    'import type { BuildOptions, EntryModel } from "./kit"',
    '',
    'type BuilderLoader = () => Promise<{ default: (options: BuildOptions) => EntryModel }>',
    '',
    'export const BUILDERS: Record<string, BuilderLoader> = {',
    ...ids.map((id) => `  '${id}': () => import('./builders/${id}'),`),
    '}',
    '',
  ]
  writeFileSync(path.join(packageRoot, 'src', 'atlas', 'three', 'builders-map.ts'), lines.join('\n'), 'utf8')
  return ids.length
}

/* ----------------------------------------------------------------------- css */

function scopeSelector(selector) {
  const trimmed = selector.trim()
  if (trimmed.length === 0) return trimmed
  const scoped = trimmed
    .split(',')
    .map((part) => {
      const piece = part.trim()
      if (piece.length === 0) return SCOPE
      if (piece === ':root') return SCOPE
      if (piece.startsWith(':root')) return SCOPE + piece.slice(':root'.length)
      if (/^html\b/.test(piece)) return piece.replace(/^html/, SCOPE)
      if (/^body\b/.test(piece)) return piece.replace(/^body/, SCOPE)
      if (/^#root\b/.test(piece)) return piece.replace(/^#root/, SCOPE)
      if (piece === '*') return `${SCOPE} *`
      return `${SCOPE} ${piece}`
    })
    .join(', ')
  return scoped
}

function scopeCss(css) {
  const root = postcss.parse(css)
  root.walkRules((rule) => {
    const parent = rule.parent
    if (parent && parent.type === 'atrule' && /keyframes$/i.test(parent.name)) return
    rule.selectors = rule.selectors.map(scopeSelector)
  })
  return root.toString()
}

/* -------------------------------------------------------------------- bundle */

const reactShim = {
  name: 'react-shim',
  setup(build) {
    build.onResolve({ filter: /^react$/ }, () => ({ path: 'react', namespace: 'sw-react' }))
    build.onLoad({ filter: /.*/, namespace: 'sw-react' }, () => ({
      contents: 'module.exports = globalThis.__SW_REACT__',
      loader: 'js',
    }))
  },
}

async function main() {
  const builderCount = generateBuildersMap()

  const desktopCss = readFileSync(path.join(packageRoot, 'src', 'atlas', 'styles', 'global.css'), 'utf8')
  const shellCss = readFileSync(path.join(packageRoot, 'src', 'client', 'atlas-host.css'), 'utf8')
  const css = `${scopeCss(desktopCss)}\n${shellCss}`

  const result = await esbuild.build({
    entryPoints: [path.join(packageRoot, 'src', 'client', 'index.tsx')],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: '__SOLIDS_CLIENT__',
    platform: 'browser',
    target: ['chrome110', 'edge110', 'firefox115', 'safari16'],
    charset: 'utf8',
    jsx: 'transform',
    jsxFactory: '__SW_H__',
    jsxFragment: '__SW_FRAGMENT__',
    minify: true,
    legalComments: 'none',
    // Pin class-field semantics instead of inheriting tsconfig.json (which exists
    // for editors). The upstream Vite build used `set` semantics; `define` would
    // silently change how three.js and React classes initialize their fields.
    tsconfigRaw: { compilerOptions: { useDefineForClassFields: false } },
    define: { __SW_CSS__: JSON.stringify(css) },
    nodePaths: moduleDirs,
    plugins: [reactShim],
    logLevel: 'warning',
  })

  const bundle = result.outputFiles[0].text
  const output = [
    '/**',
    ' * Client half of the solids-world Harness plugin.',
    ' * Generated by scripts/build.mjs — edit the sources under src/ instead.',
    ' */',
    'window.__ModuleLoader__.load({',
    `  id: '${PACKAGE_NAME}',`,
    '  factory(require) {',
    "    const React = require('react')",
    '    globalThis.__SW_REACT__ = React',
    '    globalThis.__SW_H__ = React.createElement',
    '    globalThis.__SW_FRAGMENT__ = React.Fragment',
    bundle,
    '    return __SOLIDS_CLIENT__.default()',
    '  },',
    '})',
    '',
  ].join('\n')

  const outFile = path.join(packageRoot, 'client.js')
  writeFileSync(outFile, output, 'utf8')

  const bytes = statSync(outFile).size
  console.log(`[build] builders: ${builderCount}`)
  console.log(`[build] css: ${(css.length / 1024).toFixed(1)} KiB`)
  console.log(`[build] client.js: ${(bytes / 1024).toFixed(1)} KiB`)
}

main().catch((error) => {
  console.error('[build] failed')
  console.error(error)
  process.exit(1)
})
